def _coerce_json(text: str) -> dict:
    text = text.strip()
    if "```" in text:
        # ```json ... ``` 코드블록 제거
        parts = text.split("```")
        for p in parts:
            p = p.strip()
            if p.startswith("json"):
                p = p[4:].strip()
            if p.startswith("{"):
                text = p
                break
    return json.loads(text)


def _clip(s: str) -> str:
    s = (s or "").strip()
    if len(s) <= _BLOCK_MAX:
        return s
    # 가장 늦게 등장하는 깔끔한 경계에서 자르기(문장·단어 중간 절단 방지)
    cut = s[:_BLOCK_MAX]
    best, best_len = -1, 0
    for sep in ("\n\n", "\n", "음.", "임.", "함.", "니다.", "다.", "요.", ". "):
        idx = cut.rfind(sep)
        if idx > best:
            best, best_len = idx, len(sep)
    if best > _BLOCK_MAX * 0.4:
        return cut[: best + best_len].strip()
    return cut.strip()


def generate(slot: str, table: str, date_str: str) -> list[str]:
    """slot('morning'|'noon'|'evening')에 맞춰 5개 블록 문자열을 반환."""
    header, focus = SLOT_FOCUS.get(slot, SLOT_FOCUS["evening"])

    import google.generativeai as genai

    genai.configure(api_key=config.gemini_api_key())
    model = genai.GenerativeModel(config.GEMINI_MODEL)

    prompt = _build_prompt(slot, header, focus, table, date_str)
    gen_cfg = {
        "temperature": 0.6,
        "max_output_tokens": 2048,
        # 코드블록 없이 유효한 JSON 만 받도록 강제
        "response_mime_type": "application/json",
    }

    data = None
    last_err = None
    for attempt in range(3):  # 드물게 깨진 응답이 와도 자가 복구
        try:
            resp = model.generate_content(prompt, generation_config=gen_cfg)
            data = _coerce_json(resp.text)
            break
        except Exception as e:  # noqa: BLE001
            last_err = e
            print(f"  ! 요약 파싱 실패(시도 {attempt + 1}/3): {str(e)[:80]}")
    if data is None:
        raise RuntimeError(f"요약 생성 실패: {last_err}")

    blocks = [_clip(data.get(f"block{i}", "")) for i in range(1, 6)]
    return [b for b in blocks if b]
